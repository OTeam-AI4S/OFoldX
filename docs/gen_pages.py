from typing import Any, NamedTuple

ROOT = Path(__file__).resolve().parents[1]
PACKAGE_ROOT = ROOT / "ofoldx"
ROOT_README = ROOT / "README.md"
MODEL_ROOT = PACKAGE_ROOT / "models"

