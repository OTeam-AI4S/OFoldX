ATTRIBUTE_MODULES = {
    "ofoldx.data.residue_constants",
}

Page = tuple[str, str]
NavItem = str | dict[str, Any]


class SectionEntry(NamedTuple):
    relative: PurePosixPath
    page: str
    title: str
    object_path: str
    readme: Path | None = None


def title_from_slug(slug: str) -> str:
    """Turn a package or module slug into a stable navigation label."""

    words = []
    for word in re.split(r"[-_/]+", slug):
        if not word:
            continue
        words.append(ACRONYMS.get(word.casefold(), word if any(c.isupper() for c in word[1:]) else word.capitalize()))
    return " ".join(words)


def strip_frontmatter(lines: list[str]) -> list[str]:
    if not lines or lines[0].strip() != "---":
        return lines
    for index, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            return lines[index + 1 :]
    return lines


def split_readme(readme: Path) -> tuple[str, str]:
    lines = strip_frontmatter(readme.read_text(encoding="utf-8").splitlines())
    for index, line in enumerate(lines):
        if line.startswith("# "):
            return line[2:].strip(), "\n".join(lines[index + 1 :]).lstrip()
    return title_from_slug(readme.parent.name), "\n".join(lines).lstrip()


def join_sections(*sections: str) -> str:
    return "\n\n".join(section for section in sections if section)


def relative_doc_link(page: str, target: str) -> str:
    start = PurePosixPath(page).parent.as_posix()
    return posixpath.relpath(target, start=start)


def rewrite_readme_links(body: str, *, readme: Path, page: str) -> str:
    """Translate repository README links for their generated location."""

    def replace(match: re.Match[str]) -> str:
        label, raw_target = match.groups()
        readme_root = readme.parent
        for repository_url in (REPOSITORY_BLOB_URL, REPOSITORY_TREE_URL):
            if raw_target.startswith(f"{repository_url}/"):
                raw_target = raw_target.removeprefix(f"{repository_url}/")
                readme_root = ROOT
                break
        if raw_target.startswith(("http://", "https://", "mailto:", "#")):
            return match.group(0)

        path_text, separator, fragment = raw_target.partition("#")
        if readme.parent.parent == MODEL_ROOT and path_text in {"license.md", "license-faq.md"}:
            source_target = ROOT / path_text
        else:
            source_target = (readme_root / path_text).resolve()
        if source_target.name == "README.md":
            source_target = source_target.parent

        doc_target = PACKAGE_DOC_TARGETS.get(source_target)
        if source_target.parent == MODEL_ROOT and (source_target / "model.py").exists():
            doc_target = f"models/{source_target.name}.md"
        if doc_target is not None:
            target = relative_doc_link(page, doc_target)
        elif source_target == ROOT:
            target = relative_doc_link(page, "index.md")
        elif source_target.is_relative_to(ROOT):
            repository_url = REPOSITORY_TREE_URL if source_target.is_dir() else REPOSITORY_BLOB_URL
            target = f"{repository_url}/{source_target.relative_to(ROOT).as_posix()}"
        else:
            return match.group(0)

        if separator:
            target = f"{target}#{fragment}"
        return f"[{label}]({target})"

    # Plain Markdown needs these definitions; MkDocs resolves the same references
    # against its generated API pages and the active documentation language.
    return MARKDOWN_LINK.sub(replace, API_LINK_DEFINITION.sub("", body))


def readme_page(readme: Path, page: str) -> tuple[str, str]:
    title, body = split_readme(readme)
    return title, rewrite_readme_links(body, readme=readme, page=page)


def api_directive(object_path: str, *, members: list[str] | None = None) -> str:
    lines = [
        "## API Reference",
        "",
        f"::: {object_path}",
        "    options:",
        "      show_root_heading: false",
    ]
    if members is not None:
        lines.append("      members:")
        lines.extend(f"        - {member}" for member in members)
    elif object_path in ATTRIBUTE_MODULES:
        # Descriptions live in the module's Attributes section; emit member anchors too.
        source = ROOT.joinpath(*object_path.split(".")).with_suffix(".py")
        lines.append("      members:")
        for node in ast.parse(source.read_text(encoding="utf-8")).body:
            if isinstance(node, ast.Assign):
                targets = node.targets
            elif isinstance(node, ast.AnnAssign):
                targets = [node.target]
            else:
                continue
            lines.extend(
                f"        - {binding.id}"
                for target in targets
                for binding in ast.walk(target)
                if isinstance(binding, ast.Name)
                and isinstance(binding.ctx, ast.Store)
                and not binding.id.startswith("_")
            )
    return "\n".join(lines)


def render_page(title: str, *, body: str = "", object_path: str | None = None, members: list[str] | None = None) -> str:
    api = api_directive(object_path, members=members) if object_path is not None else ""
    return join_sections(f"# {title}", body, api)


def source_has_public_api(source: Path) -> bool:
    """Include public definitions and constants, including constant-only modules."""

    tree = ast.parse(source.read_text(encoding="utf-8"))
    for node in tree.body:
        if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and not node.name.startswith("_"):
            return True
        if isinstance(node, ast.Assign):
            targets = node.targets
        elif isinstance(node, ast.AnnAssign):
            targets = [node.target]
        else:
            continue
        if any(
            isinstance(binding, ast.Name)
            and isinstance(binding.ctx, ast.Store)
            and binding.id.isupper()
            and not binding.id.startswith("_")
            for target in targets
            for binding in ast.walk(target)
        ):
            return True
    return False


def is_public_path(path: Path, root: Path) -> bool:
    return all(not part.startswith("_") for part in path.relative_to(root).parts)


def section_entries(section: str, package_root: Path, package: str) -> list[SectionEntry]:
    entries: list[SectionEntry] = []

    # Hub is a root API whose implementation is now a package; retain its reference page.
    if package_root == PACKAGE_ROOT and (package_root / "hub" / "__init__.py").exists():
        entries.append(
            SectionEntry(
                relative=PurePosixPath("hub"),
                page=f"{section}/hub.md",
                title="Hub",
                object_path=f"{package}.hub",
                readme=package_root / "hub" / "README.md",
            )
        )

    init_files = () if package_root == PACKAGE_ROOT else sorted(package_root.rglob("__init__.py"))
    for init_file in init_files:
        directory = init_file.parent
        if directory == package_root or not is_public_path(directory, package_root):
            continue
        relative_dir = directory.relative_to(package_root)
        relative = PurePosixPath(relative_dir.as_posix()) / "index"
        module_suffix = ".".join(relative_dir.parts)
        readme = directory / "README.md"
        entries.append(
            SectionEntry(
                relative=relative,
                page=f"{section}/{relative.as_posix()}.md",
                title=title_from_slug(relative_dir.name),
                object_path=f"{package}.{module_suffix}",
                readme=readme if readme.exists() else None,
            )
        )

    sources = package_root.glob("*.py") if package_root == PACKAGE_ROOT else package_root.rglob("*.py")
    for source in sorted(sources):
        if source.name == "__init__.py" or not is_public_path(source, package_root):
            continue
        if not source_has_public_api(source):
            continue
        relative_source = source.relative_to(package_root).with_suffix("")
        relative = PurePosixPath(relative_source.as_posix())
        module_suffix = ".".join(relative_source.parts)
        entries.append(
            SectionEntry(
                relative=relative,
                page=f"{section}/{relative.as_posix()}.md",
                title=title_from_slug(relative.name),
                object_path=f"{package}.{module_suffix}",
            )
        )
    return entries


def section_pages(section: str, package_root: Path, package: str) -> list[Page]:
    index_page = f"{section}/index.md"
    readme = package_root / "README.md"
    if readme.exists():
        title, body = readme_page(readme, index_page)
    else:
        title, body = title_from_slug(section), ""
    pages = [(index_page, render_page(title, body=body, object_path=package))]

    for entry in section_entries(section, package_root, package):
        if entry.readme is None:
            title, body = entry.title, ""
        else:
            title, body = readme_page(entry.readme, entry.page)
        pages.append((entry.page, render_page(title, body=body, object_path=entry.object_path)))
    return pages


def model_entries() -> list[tuple[str, Path]]:
    entries = [
        (readme.parent.name, readme)
        for readme in MODEL_ROOT.glob("*/README.md")
        if (readme.parent / "model.py").exists()
    ]
    return sorted(entries, key=lambda item: split_readme(item[1])[0].casefold())


def model_infrastructure_entries() -> list[SectionEntry]:
    entries = []
    for source in sorted(MODEL_ROOT.glob("*.py")):
        if source.name == "__init__.py" or not source_has_public_api(source):
            continue
        name = source.stem
        entries.append(
            SectionEntry(
                relative=PurePosixPath(name),
                page=f"models/{name}.md",
                title=title_from_slug(name),
                object_path=f"ofoldx.models.{name}",
            )
        )
    return entries


def model_api_members(readme: Path) -> list[str]:
    """Document model interfaces, value types, and helpers used by the README."""

    package = f"ofoldx.models.{readme.parent.name}"
    text = readme.read_text(encoding="utf-8")
    referenced = set(re.findall(rf"\]\[{re.escape(package)}\.([^.\]]+)", text))
    for code in re.findall(r"^```python\n(.*?)^```", text, re.MULTILINE | re.DOTALL):
        for node in ast.walk(ast.parse(code)):
            if isinstance(node, ast.ImportFrom) and node.module == package:
                referenced.update(alias.name for alias in node.names)

    suffixes = ("Config", "Model", "Processor", "Pipeline", "Input", "Output", "Target", "Result", "Candidate", "Loss")
    tree = ast.parse((readme.parent / "__init__.py").read_text(encoding="utf-8"))
    return [
        name
        for node in tree.body
        if isinstance(node, ast.ImportFrom) and node.level > 0
        for alias in node.names
        if not (name := alias.asname or alias.name).startswith("_")
        and name not in {"MODELS", "PIPELINES"}
        and (name.endswith(suffixes) or name in referenced)
    ]


def generated_model_pages() -> list[Page]:
    index_page = "models/index.md"
    title, body = readme_page(MODEL_ROOT / "README.md", index_page)
    pages = [(index_page, render_page(title, body=body, object_path="ofoldx.models"))]
    for model, readme in model_entries():
        page = f"models/{model}.md"
        title, body = readme_page(readme, page)
        members = model_api_members(readme)
        pages.append((page, render_page(title, body=body, object_path=f"ofoldx.models.{model}", members=members)))
    for entry in model_infrastructure_entries():
        pages.append((entry.page, render_page(entry.title, object_path=entry.object_path)))
    return pages


def generated_pages() -> list[Page]:
    home_title, home_body = readme_page(ROOT_README, "index.md")
    chinese_title, chinese_body = readme_page(ROOT / "README.zh.md", "index.zh.md")
    pages = [
        ("index.md", render_page(home_title, body=home_body)),
        ("index.zh.md", render_page(chinese_title, body=chinese_body)),
        *generated_model_pages(),
    ]
    for directory, page in PROJECT_READMES.items():
        source = directory / "README.md"
        if source.exists():
            title, body = readme_page(source, page)
            pages.append((page, render_page(title, body=body)))
    for source in sorted((*ROOT.glob("license*.md"), *ROOT.glob("privacy*.md"))):
        pages.append((f"about/{source.name}", source.read_text(encoding="utf-8")))
    for section, package_root, package in SECTION_PACKAGES.values():
        pages.extend(section_pages(section, package_root, package))
    return pages


def entry_nav(entries: list[SectionEntry]) -> list[NavItem]:
    top_level: list[SectionEntry] = []
    grouped: dict[str, list[SectionEntry]] = defaultdict(list)
    for entry in entries:
        if len(entry.relative.parts) == 1:
            top_level.append(entry)
        else:
            grouped[entry.relative.parts[0]].append(entry)

    nav: list[NavItem] = []
    nav.extend({entry.title: entry.page} for entry in sorted(top_level, key=lambda item: item.title.casefold()))
    for group, group_entries in sorted(grouped.items(), key=lambda item: title_from_slug(item[0]).casefold()):
        group_nav: list[NavItem] = []
        for section_entry in sorted(
            group_entries,
            key=lambda item: (item.relative.name != "index", item.title.casefold()),
        ):
            if section_entry.relative.name == "index":
                group_nav.append(section_entry.page)
            else:
                group_nav.append({section_entry.title: section_entry.page})
        nav.append({title_from_slug(group): group_nav})
    return nav


def section_nav(section: str, package_root: Path, package: str) -> list[NavItem]:
    return [f"{section}/index.md", *entry_nav(section_entries(section, package_root, package))]


def models_nav() -> list[NavItem]:
    nav: list[NavItem] = ["models/index.md"]
    nav.extend({split_readme(readme)[0]: f"models/{model}.md"} for model, readme in model_entries())
    infrastructure = model_infrastructure_entries()
    if infrastructure:
        nav.append({"Infrastructure": entry_nav(infrastructure)})
    return nav


def generated_nav(nav: list[Any]) -> list[Any]:
    generated: list[Any] = []
    for item in nav:
        if not isinstance(item, dict) or len(item) != 1:
            generated.append(item)
            continue
        label = next(iter(item))
        if label == "Models":
            generated.append({label: models_nav()})
        elif label in SECTION_PACKAGES:
            section, package_root, package = SECTION_PACKAGES[label]
            generated.append({label: section_nav(section, package_root, package)})
        else:
            generated.append(item)
    return generated


def write_generated(docs_dir: Path, path: str, content: str) -> None:
    output = docs_dir / path
    if output.exists() and not output.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
        return
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(f"{GENERATED_MARKER}\n\n{content.rstrip()}\n", encoding="utf-8")


def cleanup_generated(docs_dir: Path) -> None:
    for output in docs_dir.rglob("*.md"):
        if output.read_text(encoding="utf-8").startswith(GENERATED_MARKER):
            output.unlink()


def on_config(config):
    """Materialize generated pages and replace empty navigation sections."""

    docs_dir = Path(config["docs_dir"])
    cleanup_generated(docs_dir)
    for path, content in generated_pages():
        write_generated(docs_dir, path, content)
    if config.get("nav"):
        config["nav"] = generated_nav(config["nav"])
    return config


def on_post_build(config) -> None:
    cleanup_generated(Path(config["docs_dir"]))


def on_build_error(error) -> None:
    cleanup_generated(ROOT / "docs" / "docs")
