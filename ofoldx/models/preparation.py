r"""Prepare canonical molecular targets for a model and decode its predictions.

A processor returns `PreparedInput`: family-specific tensors, the resolved target,
correspondences from tensor slots to canonical atoms, the task's regeneration
scope, and a preparation record. Decoding uses those correspondences to replace
coordinates within that scope while retaining the remaining target.

Preparation checks the chemical information required by consumed atoms and records
accepted limitations elsewhere. Reference coordinates come from the value's conformer
pool or an embedding of its determined graph; a missing reference is not represented
as an invented zero conformer.

Numerical features are separate from canonical observations. Coordinate projection
selects unavailable payload out before arithmetic and dtype conversion, with zero
derivatives at excluded positions. The shared `project_coordinates` operation in
`ofoldx.modules.atom.coordinates` documents layouts and numerical checks;
`ofoldx.models.processing.project_model_coordinates` supplies contextual model
errors. These operations retain the source masks, identities, and precision of the
canonical value. A numerical API without an availability mask expects complete
finite inputs.
"""

