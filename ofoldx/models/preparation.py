I = TypeVar("I")  # noqa: E741


@dataclass(frozen=True)
class SlotMap:
    r"""Map model tensor slots to the target's canonical atoms and tokens.

    Attributes:
        atom: Canonical target atom for each slot; -1 marks an unbound slot.
        token: Token row associated with each slot.
        layout: Token layout defining those rows.
        unaddressed: Canonical target atoms that have no slot in this family's layout.
    """

    atom: NDArray[np.int64]
    token: NDArray[np.int64]
    layout: TokenLayout
    unaddressed: NDArray[np.int64]


@dataclass(frozen=True)
class RegenerationScope:
    r"""Identify the target coordinates regenerated by a task.

    Attributes:
        atoms: Boolean selection over the target atom axis, fixed during preparation.
        rule: Scope kind: none, all, components, or atoms.
        frame: Source frame or a new output frame. A new frame requires the all-atoms rule.
    """

    atoms: NDArray[np.bool_]
    rule: Literal["none", "all", "components", "atoms"]
    frame: Literal["source", "new"]

    @classmethod
    def none(cls, system: MolecularSystem) -> RegenerationScope:
        r"""No coordinate is regenerated (sequence design)."""
        return cls(np.zeros(len(system.atom_symbol), dtype=bool), "none", "source")

    @classmethod
    def all(cls, system: MolecularSystem) -> RegenerationScope:
        r"""Every coordinate is regenerated in a new frame (structure prediction)."""
        return cls(np.ones(len(system.atom_symbol), dtype=bool), "all", "new")

    @classmethod
    def components(
        cls, system: MolecularSystem, components: NDArray[np.int64], *, keep_atoms: NDArray[np.bool_] | None = None
    ) -> RegenerationScope:
        r"""Every atom of ``components`` except ``keep_atoms`` is regenerated in the source frame."""
        atoms = np.isin(_owner(system.component_atom_ptr), np.asarray(components, dtype=np.int64))
        if keep_atoms is not None:
            atoms &= ~np.asarray(keep_atoms, dtype=bool)
        return cls(atoms, "components", "source")

    @classmethod
    def atoms_of(cls, system: MolecularSystem, mask: NDArray[np.bool_]) -> RegenerationScope:
        r"""Exactly the atoms of ``mask`` are regenerated in the source frame."""
        return cls(np.array(mask, dtype=bool), "atoms", "source")


class ConformerSource(IntEnum):
    NONE = 0
    REFERENCE = 1
    EMBEDDED = 2


@dataclass(frozen=True)
class PreparationRecord:
    r"""Retain accepted preparation findings and reference-conformer sources.

    Attributes:
        records: Findings accepted while preparing the target.
        conformers: Per-component `ConformerSource` values indicating an existing
            reference, an embedded conformer, or no conformer.
    """

    records: Records
    conformers: NDArray[np.uint8]


@dataclass(frozen=True)
class PreparationContext:
    r"""Canonical correspondence and information retained for target alignment and decoding.

    Attributes:
        structure: Canonical structure represented by the prepared features.
        slots: Correspondence between feature slots and canonical atoms.
        scope: Coordinate range regenerated by the task.
        record: Preparation findings and conformer sources.
    """

    structure: Structure
    slots: SlotMap
    scope: RegenerationScope
    record: PreparationRecord
    spec: PreparationSpec | None = None


@dataclass(frozen=True)
class PreparedInput(Generic[I]):
    r"""Task features together with the context needed to align truth and decode predictions.

    `features` are the family's base representation, not an arbitrary complete
    forward batch. Teacher-forcing history, corruption, and noise belong to the
    concrete execution protocol.
    """

    features: I
    context: PreparationContext


def _owner(pointer: NDArray[np.int64]) -> NDArray[np.int64]:
    return np.repeat(np.arange(len(pointer) - 1, dtype=np.int64), np.diff(pointer))


def decode_coordinates(
    prepared: PreparedInput[I],
    coordinates: NDArray[np.float64],
    *,
    valid: NDArray[np.bool_] | None = None,
    evidence: CoordinateEvidence = CoordinateEvidence.PREDICTED,
) -> tuple[Structure, CoordinateReport]:
    r"""Apply predicted slot coordinates to the prepared target.

    Args:
        prepared: Input and canonical correspondences returned by preparation.
        coordinates: XYZ values over the prepared slot axis.
        valid: Optional mask selecting slots with predicted coordinates. Unbound
            slots are excluded independently of this mask.
        evidence: Evidence class assigned to the new coordinates.

    Returns:
        The updated structure and a report of coordinate changes.

    Raises:
        InvalidRequestError: A predicted bound slot lies outside the regeneration
            scope (`scope_violation`), or the coordinate replacement request is invalid.

    Notes:
        Atoms inside the scope use this output only. Unpredicted atoms become
        unavailable and are counted in the report; atoms outside the scope retain
        their existing information. Coordinate replacement follows the prepared frame.
    """

    atom = prepared.context.slots.atom
    bound = atom >= 0 if valid is None else np.asarray(valid, dtype=bool) & (atom >= 0)
    return replace_coordinates(
        prepared.context.structure,
        atom[bound],
        np.asarray(coordinates, dtype=np.float64)[bound],
        scope=prepared.context.scope.atoms,
        evidence=evidence,
        frame=prepared.context.scope.frame,
    )


@dataclass(frozen=True)
class GatingPolicy:
    r"""
    What a family refuses at the atoms it consumes. ``required_states`` names atom columns whose state must be
    KNOWN on every slot atom (e.g. ``"formal_charge"``: a canonical zero is never fed as a value).
    """

    refuse_undetermined_in_slots: bool = True
    refuse_unknown_kind_in_slots: bool = True
    refuse_incomplete_topology_in_slots: bool = True
    refuse_valence_excess: bool = True
    required_states: frozenset[str] = frozenset()


def component_records(code: str, components: NDArray[np.int64], first_slot=None) -> Records:
    r"""Records of one code, one per component subject, without source references; ``first_slot`` fills payload 0."""
    count = len(components)
    payload = np.zeros((count, 4), dtype=np.int64)
    if first_slot is not None:
        payload[:, 0] = first_slot
    empty = Records.empty()
    return Records(
        np.full(count, CODE_NAMES.index(code), dtype=np.uint16),
        np.full(count, SubjectKind.COMPONENT, dtype=np.uint8),
        np.asarray(components, dtype=np.int64),
        np.zeros(count + 1, dtype=np.int64),
        np.zeros(0, dtype=np.int64),
        empty.refs,
        payload,
        np.zeros(count + 1, dtype=np.int64),
        np.zeros(0, dtype=np.int64),
        (),
    )


def _per_atom_components(slots: SlotMap, atom_component: NDArray[np.int64], count: int) -> NDArray[np.bool_]:
    r"""
    Per component, whether the layout tokenizes it per atom: its slot atoms are as many as its tokens, and it has
    several tokens or no polymer class (a residue token with one slot is not per atom).
    """

    bound = slots.atom >= 0
    slot_count = np.bincount(atom_component[slots.atom[bound]], minlength=count)
    layout = slots.layout
    token_count = np.bincount(layout.token_component, minlength=count)
    other = np.zeros(count, dtype=bool)
    other[layout.token_component] = layout.token_class == TOKEN_INDEX["OTHER"]
    return (slot_count > 0) & (slot_count == token_count) & ((token_count > 1) | other)


def _incomplete_causes(system: MolecularSystem, components: NDArray[np.int64]) -> NDArray[np.int64]:
    r"""
    Per incomplete component, the ``CODE_NAMES`` index of what its value shows: an incident connection of unknown kind
    (``kind_unknown``), a covalent one of unknown order (``order_unknown``), else ``prepare_incomplete_topology``.
    """

    s = system.arrays()
    count = len(s["component_symbol"])
    atom_component = _owner(s["component_atom_ptr"])
    ends = [(s["edge_index"][0], "bond"), (s["edge_index"][1], "bond"), (s["external_atom"], "external")]
    kind_unknown, order_unknown = np.zeros(count, dtype=bool), np.zeros(count, dtype=bool)
    for atoms, prefix in ends:
        owner = atom_component[atoms.astype(np.int64)]
        kind_known = known(s[f"{prefix}_kind_state"])
        covalent = kind_known & (s[f"{prefix}_kind"] == BondKind.COVALENT)
        kind_unknown[owner[~kind_known]] = True
        order_unknown[owner[covalent & ~known(s[f"{prefix}_order_state"])]] = True
    codes = np.full(count, CODE_NAMES.index("prepare_incomplete_topology"), dtype=np.int64)
    codes[order_unknown] = CODE_NAMES.index("order_unknown")
    codes[kind_unknown] = CODE_NAMES.index("kind_unknown")
    return codes[components]


def gate(target: Structure, slots: SlotMap, policy: GatingPolicy) -> Records:
    r"""
    Refuse what the consumed atoms (the slot atoms) cannot be fed with; record the accepted incompleteness.

    In order: under every policy, a CONFLICT endpoint at a slot atom or at an atom bonded to one
    (``prepare_source_conflict``), since a slot atom's connections and fate hang on the attachment at both ends of its
    bonds; a Conflict elsewhere in the value is not refused. Then, as the policy says: an UNDETERMINED atom or an
    UNKNOWN endpoint bound to a slot (``prepare_undetermined_slot``); an edge of unknown kind between slot atoms
    (``prepare_unknown_kind``, naming the assumption rule a consumer may read with); a slot atom of a definition-less
    component, or a per-atom tokenized component whose topology is incomplete (``prepare_incomplete_topology``); a
    required state not KNOWN on a slot atom (``prepare_unknown_feature``); a KNOWN positive valence excess at a slot
    atom (``prepare_valence_excess``). Every component whose topology claim is False and that was not refused gets one
    ``prepare_accepted_incomplete`` record naming the cause its value shows.
    """

    system = target.system
    s = system.arrays()
    count = len(s["component_symbol"])
    atom_component = _owner(s["component_atom_ptr"])
    consumed = np.zeros(len(s["atom_symbol"]), dtype=bool)
    consumed[slots.atom[slots.atom >= 0]] = True
    first, second = s["edge_index"].astype(np.int64)
    resolution = endpoint_resolution(s["atom_endpoint_state"])

    def refuse(code: str, atoms: NDArray[np.int64], **detail: object) -> None:
        if len(atoms):
            atom = int(atoms[0])
            fail(code, StructureRef(component=int(atom_component[atom]), atom=atom), **detail)

    reached = consumed.copy()
    reached[first[consumed[second]]] = True
    reached[second[consumed[first]]] = True
    refuse("prepare_source_conflict", np.flatnonzero(reached & (resolution == Resolution.CONFLICT)))
    if policy.refuse_undetermined_in_slots:
        undetermined = (s["atom_fate"] == AtomFate.UNDETERMINED) | (resolution == Resolution.UNKNOWN)
        refuse("prepare_undetermined_slot", np.flatnonzero(consumed & undetermined))
    if policy.refuse_unknown_kind_in_slots:
        unknown = consumed[first] & consumed[second] & ~known(s["bond_kind_state"])
        refuse("prepare_unknown_kind", first[unknown], rule="link_metal_coordination")
    if policy.refuse_incomplete_topology_in_slots:
        definitionless = s["component_definition_scope"] == DefinitionScope.NONE
        refuse("prepare_incomplete_topology", np.flatnonzero(consumed & definitionless[atom_component]))
        open_per_atom = _per_atom_components(slots, atom_component, count) & ~s["component_topology_complete"]
        refuse("prepare_incomplete_topology", np.flatnonzero(consumed & open_per_atom[atom_component]))
    for name in sorted(policy.required_states):
        refuse("prepare_unknown_feature", np.flatnonzero(consumed & ~known(s[f"{name}_state"])), column=name)
    if policy.refuse_valence_excess:
        excess = valence_excess(system)
        positive = excess.atom[known(excess.state) & (excess.excess > 0)]
        refuse("prepare_valence_excess", positive[consumed[positive]])
    incomplete = np.flatnonzero(~s["component_topology_complete"])
    return component_records("prepare_accepted_incomplete", incomplete, _incomplete_causes(system, incomplete))


def missing_reference(system: MolecularSystem) -> NDArray[np.bool_]:
    r"""Per component: some atom has no usable reference conformer (pool source ``NONE`` or ``CONTRADICTED``)."""
    _, source = system.reference_coordinates()
    usable = np.isin(source, (ReferenceSource.IDEAL, ReferenceSource.MODEL))
    count = len(system.component_symbol)
    return np.bincount(_owner(system.component_atom_ptr)[~usable], minlength=count) > 0


def reference_conformers(
    target: Structure, slots: SlotMap, *, embed: NDArray[np.bool_], seed: int
) -> tuple[NDArray[np.float64], NDArray[np.uint8], Records]:
    r"""
    Per slot, its reference conformer coordinates and their ``ConformerSource``.

    Usability is decided at the slot atoms only: a component whose every slot atom has a usable pool row
    (IDEAL/MODEL) takes the pool's coordinates, whatever its unconsumed atoms lack. The other slot components must be
    marked in ``embed`` (per component) and are embedded from the determined graph by
    ``chemistry.rdkit.embed_conformer`` with ``seed`` — a non-polymer instance whole (a part of it cuts edges), a
    polymer component alone — and each gets one ``reference_embedded`` record. A slot component lacking a usable
    reference that is not marked is ``InsufficientInformationError(prepare_reference_missing)``; a refused projection
    is the same condition, an exhausted search ``ResourceLimitError(embedding_failed)``. Slots bound to no atom stay
    zero with source ``NONE``.
    """

    system = target.system
    s = system.arrays()
    pool, pool_source = system.reference_coordinates()
    atom_component = _owner(s["component_atom_ptr"])
    component_instance = _owner(s["instance_component_ptr"])
    entity = s["instance_entity"]
    polymer = known(s["entity_type_state"][entity]) & (s["entity_type"][entity] == EntityType.POLYMER)
    embed = np.asarray(embed, dtype=bool)
    bound = slots.atom >= 0
    atom = slots.atom[bound]
    usable = np.isin(pool_source[atom], (ReferenceSource.IDEAL, ReferenceSource.MODEL))
    lacking = np.unique(atom_component[atom[~usable]])
    if len(lacking) and not embed[lacking].all():
        fail("prepare_reference_missing", StructureRef(component=int(lacking[~embed[lacking]][0])))
    slot_component = np.where(bound, atom_component[np.maximum(slots.atom, 0)], -1)
    take = bound & ~np.isin(slot_component, lacking)
    coordinates = np.zeros((len(slots.atom), 3), dtype=np.float64)
    source = np.zeros(len(slots.atom), dtype=np.uint8)
    coordinates[take] = pool[slots.atom[take]]
    source[take] = ConformerSource.REFERENCE
    for instance in np.unique(component_instance[lacking]).tolist():
        group = lacking[component_instance[lacking] == instance]
        members = group if polymer[instance] else np.flatnonzero(component_instance == instance)
        atoms = np.flatnonzero(np.isin(atom_component, members))
        conformer = embed_conformer(system, atoms, seed=seed)
        if isinstance(conformer, EmbeddingFailed):
            code = "embedding_failed" if conformer.reason == "exhausted" else "prepare_reference_missing"
            fail(code, StructureRef(instance=instance, component=int(group[0])), reason=conformer.reason)
        position = np.full(len(atom_component), -1, dtype=np.int64)
        position[atoms] = np.arange(len(atoms))
        rows = bound & np.isin(slot_component, group)
        coordinates[rows] = conformer.coordinates[position[slots.atom[rows]]]
        source[rows] = ConformerSource.EMBEDDED
    return coordinates, source, component_records("reference_embedded", lacking, seed)
